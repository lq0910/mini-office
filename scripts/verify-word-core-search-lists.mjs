/** 功能：通过真实产品按钮/键盘验收查找替换、列表层级、下载和重开；时间：2026-11-10；作者：lq。 */
import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';
import JSZip from 'jszip';

const root = resolve(import.meta.dirname, '..');
const output = join(root, 'output/playwright/word-core-m3-search-lists.local');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true, executablePath: process.env.MINI_OFFICE_CHROME ?? join(homedir(), 'Library/Caches/ms-playwright/chromium-1217/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing') });
const report = { status: 'running', checks: [], errors: [] };
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
  page.setDefaultTimeout(20000);
  page.on('pageerror', error => report.errors.push(String(error)));
  await page.addInitScript(() => { window.showSaveFilePicker = undefined; });
  await page.goto(process.env.MINI_OFFICE_TEST_URL ?? 'http://127.0.0.1:1431');
  await page.getByRole('button', { name: 'DOCX 文件 Word 文档' }).click();
  const editor = page.locator('[data-word-engine="word-core"] .ProseMirror');
  await editor.click();
  await page.keyboard.insertText('Ab');
  await page.getByRole('button', { name: '加粗', exact: true }).click();
  await page.keyboard.insertText('c abc 中文');
  await page.keyboard.press('Enter');
  await page.keyboard.insertText('ABC abc 中文');
  // 功能：检查入口只读取同一会话状态，不用内部命令替代用户操作；时间：2026-11-10；作者：lq。
  await page.evaluate(async root => {
    const { useWorkspaceStore } = await import('/@fs' + root + '/packages/document-model/src/index.ts');
    window.__listStore = useWorkspaceStore;
    window.__listCore = () => useWorkspaceStore.getState().sessions[useWorkspaceStore.getState().activeId].wordCore;
  }, root);
  const revision = await page.evaluate(() => window.__listCore().state().revision);
  await page.getByRole('button', { name: '查找替换', exact: true }).click();
  const panel = page.getByRole('search', { name: '查找替换' });
  const query = panel.getByRole('textbox', { name: '查找内容' });
  const replacement = panel.getByRole('textbox', { name: '替换为' });
  await query.fill('abc');
  await page.waitForFunction(() => document.querySelector('[aria-label="查找结果"]')?.textContent === '1/4');
  assert.equal(await editor.locator('.search-hit').allTextContents().then(texts => texts.join('')), 'AbcabcABCabc');
  assert.equal(await page.evaluate(() => window.__listCore().state().revision), revision);
  await panel.getByRole('checkbox', { name: '区分大小写' }).check();
  await page.waitForFunction(() => document.querySelector('[aria-label="查找结果"]')?.textContent === '1/2');
  await panel.getByRole('checkbox', { name: '区分大小写' }).uncheck();
  await query.press('Enter');
  await page.waitForFunction(() => document.querySelector('[aria-label="查找结果"]')?.textContent === '2/4');
  assert.equal(await page.evaluate(() => { const e = window.__listCore().editor; return e.state.doc.textBetween(e.state.selection.from, e.state.selection.to); }), 'abc');
  await query.press('Shift+Enter');
  await page.waitForFunction(() => document.querySelector('[aria-label="查找结果"]')?.textContent === '1/4');
  await page.screenshot({ path: join(output, 'find-highlights.png') });
  report.checks.push('cross-format-search-visible-highlights', 'search-does-not-change-revision', 'case-sensitive-result-count', 'enter-shift-enter-native-selection');
  await replacement.fill('替换');
  await panel.getByRole('button', { name: '全部替换', exact: true }).click();
  await page.waitForFunction(() => window.__listCore().editor.state.doc.textContent === '替换 替换 中文替换 替换 中文');
  await panel.getByRole('button', { name: '关闭', exact: true }).click();
  assert.equal(await editor.locator('.search-hit').count(), 0);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  assert.equal(await page.evaluate(() => window.__listCore().editor.state.doc.textContent), 'Abc abc 中文ABC abc 中文');
  await page.getByRole('button', { name: '重做', exact: true }).click();
  // 功能：外壳快捷键必须真正打开同一个查找浮层，输入框 Esc 退出不会改变正文；时间：2026-11-10；作者：lq。
  await page.keyboard.press('Meta+f');
  await query.waitFor();
  await query.fill('中文');
  await page.waitForFunction(() => document.querySelector('[aria-label="查找结果"]')?.textContent === '1/2');
  await replacement.fill('汉字');
  await panel.getByRole('button', { name: '替换', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[aria-label="查找结果"]')?.textContent === '1/1');
  await query.press('Escape');
  await panel.waitFor({ state: 'detached' });
  report.checks.push('replace-all-single-undo-redo', 'close-clears-highlights', 'shell-find-shortcut-and-escape', 'single-replace-recomputes-results');

  await page.keyboard.press('Meta+a');
  await page.getByRole('button', { name: '编号', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: '编号', exact: true }).getAttribute('aria-pressed'), 'true');
  assert.equal(await editor.locator('.doc-li-ordered').count(), 2);
  const numId = await page.evaluate(() => window.__listCore().editor.state.doc.firstChild.attrs.numId);
  await page.getByRole('button', { name: '增加缩进', exact: true }).click();
  assert.deepEqual(await page.evaluate(() => window.__listCore().editor.getJSON().content.map(node => node.attrs.ilvl)), [1, 1]);
  await page.getByRole('button', { name: '减少缩进', exact: true }).click();
  await page.getByRole('button', { name: '项目符号', exact: true }).click();
  assert.equal(await editor.locator('.doc-li-bullet').count(), 2);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  assert.equal(await editor.locator('.doc-li-ordered').count(), 2);
  assert.equal(await page.evaluate(() => window.__listCore().editor.state.doc.firstChild.attrs.numId), numId);
  report.checks.push('list-buttons-and-active-state', 'list-indent-buttons-change-real-levels', 'list-type-change-single-undo');
  // 功能：真实 Enter 续号、空项退出和 Tab 层级继续采用核心规则；时间：2026-11-10；作者：lq。
  await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => window.__listCore().editor.state.selection.empty);
  await page.keyboard.press('Meta+ArrowDown');
  await page.waitForFunction(() => { const e = window.__listCore().editor; return e.state.selection.to === e.state.doc.content.size - 1; });
  await page.keyboard.press('Enter');
  await page.keyboard.insertText('第三条');
  assert.equal(await editor.locator('.doc-li-ordered').count(), 3);
  await page.keyboard.press('Meta+ArrowLeft');
  await page.waitForFunction(() => window.__listCore().editor.state.selection.$from.parentOffset === 0);
  await page.keyboard.press('Tab');
  assert.equal(await page.evaluate(() => window.__listCore().editor.state.selection.$from.parent.attrs.ilvl), 1);
  await page.keyboard.press('Shift+Tab');
  assert.equal(await page.evaluate(() => window.__listCore().editor.state.selection.$from.parent.attrs.ilvl), 0);
  await page.keyboard.press('Meta+ArrowDown');
  await page.waitForFunction(() => { const e = window.__listCore().editor; return e.state.selection.to === e.state.doc.content.size - 1; });
  await page.keyboard.press('Enter');
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(() => window.__listCore().editor.state.selection.$from.parent.type.name), 'docParagraph');
  report.checks.push('enter-continues-list-empty-item-exits', 'tab-shift-tab-change-levels');
  await page.screenshot({ path: join(output, 'lists.png') });

  const pending = page.waitForEvent('download');
  await page.getByRole('button', { name: '保存', exact: true }).click();
  const download = await pending;
  const path = join(output, 'search-lists-saved.docx');
  await download.saveAs(path);
  const bytes = await readFile(path);
  const zip = await JSZip.loadAsync(bytes);
  const xml = await zip.file('word/document.xml').async('text');
  assert.ok(xml.includes('第三条')); assert.ok(xml.includes('汉字')); assert.ok(!xml.includes('Abc'));
  assert.ok(xml.includes(`w:numId w:val="${numId}"`));
  const numbering = await zip.file('word/numbering.xml').async('text');
  assert.ok(numbering.includes(`w:numId="${numId}"`));
  const beforeText = await page.evaluate(() => window.__listCore().editor.state.doc.textContent);
  await page.evaluate(bytes => window.__listStore.getState().openBytes({ name: '查找列表重开.docx', bytes: new Uint8Array(bytes) }), Array.from(bytes));
  await page.waitForFunction(text => window.__listCore().editor.state.doc.textContent === text && window.__listCore().state().dirty === false, beforeText);
  assert.equal(await editor.locator('.doc-li-ordered').count(), 3);
  assert.deepEqual(await page.evaluate(() => window.__listCore().editor.getJSON().content.filter(node => node.type === 'docListItem').map(node => node.attrs.numId)), [numId, numId, numId]);
  report.checks.push('actual-download-docx-text-and-numbering', 'reopen-preserves-list-identity-and-text');
  assert.deepEqual(report.errors, []);
  report.status = 'passed'; report.browser = browser.version();
} catch (error) { report.status = 'failed'; report.error = String(error); report.stack = error.stack; report.diagnostic = await browser.contexts()[0]?.pages()[0]?.evaluate(() => ({ doc: window.__listCore?.().editor.getJSON(), selection: window.__listCore?.().editor.state.selection.toJSON(), active: document.activeElement?.outerHTML.slice(0, 300) })); await browser.contexts()[0]?.pages()[0]?.screenshot({ path: join(output, 'failure.png') }); process.exitCode = 1; }
finally { await browser.close(); await writeFile(join(output, 'report.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report)); }
